const compiled = rules.map(function(rule) {
  return { pattern: new RegExp("(?:^|[^a-z0-9])(?:" + rule.pattern + ")(?:$|[^a-z0-9])", "i"),
    icon: rule.icon }
})

export function resolve(appClass, desktopId) {
  var candidates = [String(appClass || ""), String(desktopId || "")]
  // The live window app ID takes precedence over desktop-entry heuristics.
  for (var c = 0; c < candidates.length; c++) {
    if (!candidates[c]) continue
    for (var i = 0; i < compiled.length; i++)
      if (compiled[i].pattern.test(candidates[c])) return compiled[i].icon
  }
  return ""
}
